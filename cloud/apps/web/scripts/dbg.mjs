import { chromium } from '@playwright/test';
const BASE = 'http://localhost:5201';
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 402, height: 874 }, isMobile: true, hasTouch: true });
const page = await context.newPage();
page.setDefaultTimeout(15000);
await page.goto(BASE);
await page.evaluate(() => fetch('/v1/auth/dev', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ type: 'auth.dev' }) }));
await page.reload();
await page.waitForTimeout(1500);
await page.evaluate(() => { history.pushState({}, '', '/settings/account'); window.dispatchEvent(new PopStateEvent('popstate')); });
await page.waitForTimeout(1500);
console.log('settings-page count:', await page.getByTestId('settings-page').count());
console.log('Close settings count:', await page.getByRole('button', { name: 'Close settings' }).count());
console.log('body:', (await page.locator('body').innerText()).slice(0, 400));
await context.close();
await browser.close();
